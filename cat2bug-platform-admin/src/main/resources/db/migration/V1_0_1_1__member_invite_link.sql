CREATE TABLE IF NOT EXISTS sys_member_invite (
    invite_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(64) NOT NULL,
    scope VARCHAR(16) NOT NULL,
    team_id BIGINT NOT NULL,
    project_id BIGINT,
    role_ids VARCHAR(512) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked TINYINT NOT NULL DEFAULT 0,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_member_invite_token ON sys_member_invite (token);
CREATE INDEX IF NOT EXISTS idx_sys_member_invite_team ON sys_member_invite (team_id);
CREATE INDEX IF NOT EXISTS idx_sys_member_invite_project ON sys_member_invite (project_id);
