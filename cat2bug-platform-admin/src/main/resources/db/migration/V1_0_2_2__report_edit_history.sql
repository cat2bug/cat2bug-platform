-- 报告正文编辑历史：每次成功保存且正文有变更时写入一条记录（谁、何时、当时正文快照）
CREATE TABLE IF NOT EXISTS sys_report_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL,
    report_description CLOB,
    create_by_id BIGINT,
    create_time TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sys_report_history_report_id ON sys_report_history (report_id);
CREATE INDEX IF NOT EXISTS idx_sys_report_history_create_time ON sys_report_history (create_time);
