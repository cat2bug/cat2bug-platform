-- Cat2Bug 1.1.0 迁移 #40: access_token_oauth
-- 个人访问令牌、OAuth 客户端与授权码（只存哈希）
CREATE TABLE IF NOT EXISTS sys_user_access_token (
  token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  name VARCHAR(128) NOT NULL,
  token_hash VARCHAR(64) NOT NULL,
  token_prefix VARCHAR(16) NOT NULL,
  source VARCHAR(16) NOT NULL,
  client_id VARCHAR(64),
  grant_id VARCHAR(64),
  resource VARCHAR(500),
  expires_at TIMESTAMP,
  last_used_at TIMESTAMP,
  last_used_ip VARCHAR(128),
  revoked_at TIMESTAMP,
  create_time TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_access_token_hash
  ON sys_user_access_token (token_hash);
CREATE INDEX IF NOT EXISTS idx_sys_user_access_token_user
  ON sys_user_access_token (user_id, source);
CREATE INDEX IF NOT EXISTS idx_sys_user_access_token_grant
  ON sys_user_access_token (grant_id);

CREATE TABLE IF NOT EXISTS sys_oauth_client (
  client_id VARCHAR(64) NOT NULL PRIMARY KEY,
  client_name VARCHAR(255) NOT NULL,
  redirect_uris VARCHAR(4000) NOT NULL,
  create_time TIMESTAMP,
  last_used_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_oauth_code (
  code_hash VARCHAR(64) NOT NULL PRIMARY KEY,
  client_id VARCHAR(64) NOT NULL,
  user_id BIGINT NOT NULL,
  redirect_uri VARCHAR(2000) NOT NULL,
  code_challenge VARCHAR(128) NOT NULL,
  resource VARCHAR(500),
  expires_at TIMESTAMP NOT NULL,
  used TINYINT NOT NULL DEFAULT 0,
  create_time TIMESTAMP
);
