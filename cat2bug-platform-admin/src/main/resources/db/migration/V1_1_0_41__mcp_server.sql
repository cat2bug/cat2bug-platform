-- 项目 MCP 设置、缺陷修复关联提交、MCP 幂等记录；操作日志与缺陷日志增加来源渠道与客户端
CREATE TABLE IF NOT EXISTS sys_project_mcp (
  project_id BIGINT NOT NULL PRIMARY KEY,
  enabled INT NOT NULL DEFAULT 0,
  modules VARCHAR(1000) NOT NULL,
  update_by VARCHAR(64),
  update_time TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_defect_commit (
  commit_link_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  defect_id BIGINT NOT NULL,
  defect_log_id BIGINT,
  repository_id BIGINT,
  commit_sha VARCHAR(64) NOT NULL,
  commit_url VARCHAR(1000),
  commit_message VARCHAR(1000),
  commit_time TIMESTAMP,
  create_by VARCHAR(64),
  create_time TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sys_defect_commit_defect ON sys_defect_commit (defect_id);
CREATE INDEX IF NOT EXISTS idx_sys_defect_commit_log ON sys_defect_commit (defect_log_id);

CREATE TABLE IF NOT EXISTS sys_mcp_idempotency (
  user_id BIGINT NOT NULL,
  tool VARCHAR(64) NOT NULL,
  idem_key VARCHAR(128) NOT NULL,
  result_id VARCHAR(64) NOT NULL,
  create_time TIMESTAMP NOT NULL,
  PRIMARY KEY (user_id, tool, idem_key)
);

ALTER TABLE sys_oper_log ADD COLUMN IF NOT EXISTS oper_channel VARCHAR(16);
ALTER TABLE sys_oper_log ADD COLUMN IF NOT EXISTS client_name VARCHAR(128);
ALTER TABLE sys_defect_log ADD COLUMN IF NOT EXISTS oper_channel VARCHAR(16);
ALTER TABLE sys_defect_log ADD COLUMN IF NOT EXISTS client_name VARCHAR(128);
