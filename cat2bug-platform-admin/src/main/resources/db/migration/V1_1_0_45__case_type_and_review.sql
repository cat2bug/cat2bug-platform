CREATE TABLE IF NOT EXISTS sys_case_type (
  type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  type_name VARCHAR(64) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  CONSTRAINT uk_case_type_project_name UNIQUE (project_id, type_name)
);

CREATE TABLE IF NOT EXISTS sys_case_review (
  review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  status VARCHAR(16) NOT NULL,
  report_markdown CLOB,
  create_by VARCHAR(64),
  create_time TIMESTAMP,
  complete_by VARCHAR(64),
  complete_time TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_case_review_item (
  item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id BIGINT NOT NULL,
  case_id BIGINT NOT NULL,
  verdict VARCHAR(16) NOT NULL,
  item_comment VARCHAR(2000),
  CONSTRAINT uk_case_review_item UNIQUE (review_id, case_id)
);

CREATE INDEX IF NOT EXISTS idx_case_review_project ON sys_case_review (project_id, status);
CREATE INDEX IF NOT EXISTS idx_case_review_item_case ON sys_case_review_item (case_id);

ALTER TABLE sys_case ADD COLUMN IF NOT EXISTS review_status VARCHAR(16);
ALTER TABLE sys_project ADD COLUMN IF NOT EXISTS case_review_template CLOB;

INSERT INTO sys_case_type (project_id, type_name, sort_order)
SELECT p.project_id, t.type_name, t.sort_order
FROM sys_project p
CROSS JOIN (
  SELECT '功能' AS type_name, 1 AS sort_order
  UNION ALL SELECT '接口', 2
  UNION ALL SELECT '界面', 3
) t
WHERE NOT EXISTS (
  SELECT 1 FROM sys_case_type c
  WHERE c.project_id = p.project_id AND c.type_name = t.type_name
);

