CREATE TABLE IF NOT EXISTS sys_user_workbench (
  workbench_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  project_id BIGINT NOT NULL,
  config_json CLOB,
  create_time TIMESTAMP,
  update_time TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_workbench_user_project
  ON sys_user_workbench (user_id, project_id);
