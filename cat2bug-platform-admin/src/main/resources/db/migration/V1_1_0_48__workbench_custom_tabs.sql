-- H2。脚本可重复执行。

CREATE TABLE IF NOT EXISTS sys_project_workbench_tabs (
  tab_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  owner_user_id BIGINT NOT NULL,
  visibility VARCHAR(16) NOT NULL,
  tab_name VARCHAR(64) NOT NULL,
  preset VARCHAR(32),
  config_json CLOB,
  tab_sort BIGINT,
  create_time TIMESTAMP,
  update_time TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_wb_tabs_project_visibility
  ON sys_project_workbench_tabs (project_id, visibility);

CREATE INDEX IF NOT EXISTS idx_wb_tabs_project_owner
  ON sys_project_workbench_tabs (project_id, owner_user_id);
