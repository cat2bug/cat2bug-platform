-- 缺陷甘特二期：计划依赖边 + 项目活跃基线快照（H2）

CREATE TABLE IF NOT EXISTS sys_defect_plan_link (
  link_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  from_defect_id BIGINT NOT NULL,
  to_defect_id BIGINT NOT NULL,
  link_type VARCHAR(8) NOT NULL DEFAULT 'FS',
  create_by VARCHAR(64),
  create_time TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_defect_plan_link
  ON sys_defect_plan_link (from_defect_id, to_defect_id, link_type);

CREATE INDEX IF NOT EXISTS idx_defect_plan_link_project
  ON sys_defect_plan_link (project_id);

CREATE INDEX IF NOT EXISTS idx_defect_plan_link_from
  ON sys_defect_plan_link (from_defect_id);

CREATE INDEX IF NOT EXISTS idx_defect_plan_link_to
  ON sys_defect_plan_link (to_defect_id);

CREATE TABLE IF NOT EXISTS sys_defect_plan_baseline (
  baseline_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id BIGINT NOT NULL,
  frozen_by VARCHAR(64),
  frozen_time TIMESTAMP,
  CONSTRAINT uk_defect_plan_baseline_project UNIQUE (project_id)
);

CREATE TABLE IF NOT EXISTS sys_defect_plan_baseline_item (
  item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  baseline_id BIGINT NOT NULL,
  defect_id BIGINT NOT NULL,
  plan_start_time TIMESTAMP,
  plan_end_time TIMESTAMP,
  CONSTRAINT uk_defect_plan_baseline_item UNIQUE (baseline_id, defect_id)
);

CREATE INDEX IF NOT EXISTS idx_defect_plan_baseline_item_base
  ON sys_defect_plan_baseline_item (baseline_id);
