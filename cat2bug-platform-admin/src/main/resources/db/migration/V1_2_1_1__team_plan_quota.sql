-- 团队套餐（角色）配额 + 项目已用空间；Admin「团队角色」菜单

CREATE TABLE IF NOT EXISTS sys_team_plan (
  plan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_name VARCHAR(64) NOT NULL,
  max_members INT NOT NULL DEFAULT 10,
  max_projects INT NOT NULL DEFAULT 20,
  max_project_bytes BIGINT NOT NULL DEFAULT 1073741824,
  is_system_default SMALLINT NOT NULL DEFAULT 0,
  remark VARCHAR(255),
  create_by VARCHAR(64),
  create_time TIMESTAMP,
  update_by VARCHAR(64),
  update_time TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_team_plan_name ON sys_team_plan (plan_name);

