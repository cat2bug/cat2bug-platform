-- Cat2Bug 1.1.0 迁移 #6: git_repo_collect
-- 用户关注（收藏）代码仓库

CREATE TABLE IF NOT EXISTS sys_user_git_repository (
  user_git_repository_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  repository_id BIGINT NOT NULL,
  collect INT NOT NULL DEFAULT 0,
  create_by VARCHAR(64),
  create_time TIMESTAMP,
  update_by VARCHAR(64),
  update_time TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_git_repository ON sys_user_git_repository (user_id, repository_id);
CREATE INDEX IF NOT EXISTS idx_sys_user_git_repository_repo ON sys_user_git_repository (repository_id);
