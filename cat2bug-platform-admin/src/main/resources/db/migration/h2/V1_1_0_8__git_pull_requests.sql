-- Cat2Bug 1.1.0 迁移 #8: git_pull_requests
-- Pull Request 元数据与整单讨论评论
CREATE TABLE IF NOT EXISTS sys_git_pull_request (
  pull_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_id BIGINT NOT NULL,
  number INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  body CLOB,
  source_branch VARCHAR(255) NOT NULL,
  target_branch VARCHAR(255) NOT NULL,
  source_sha VARCHAR(64),
  target_sha VARCHAR(64),
  state VARCHAR(16) NOT NULL DEFAULT 'open',
  author_id BIGINT NOT NULL,
  merged_by BIGINT,
  merged_at TIMESTAMP,
  closed_at TIMESTAMP,
  create_by VARCHAR(64),
  create_time TIMESTAMP,
  update_by VARCHAR(64),
  update_time TIMESTAMP,
  remark VARCHAR(500)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_git_pull_request_repo_number
  ON sys_git_pull_request (repository_id, number);
CREATE INDEX IF NOT EXISTS idx_sys_git_pull_request_repo
  ON sys_git_pull_request (repository_id);

CREATE TABLE IF NOT EXISTS sys_git_pull_request_comment (
  comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pull_request_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  body CLOB NOT NULL,
  parent_id BIGINT,
  create_time TIMESTAMP,
  update_time TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sys_git_pull_request_comment_pr
  ON sys_git_pull_request_comment (pull_request_id);
