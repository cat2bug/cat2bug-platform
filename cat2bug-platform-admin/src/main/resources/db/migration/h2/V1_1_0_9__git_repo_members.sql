-- Cat2Bug 1.1.0 迁移 #9: git_repo_members
-- 仓级 ACL：用户 × 仓库 × 角色（read|write|admin）
CREATE TABLE IF NOT EXISTS sys_git_repository_member (
  member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  role VARCHAR(16) NOT NULL,
  create_by VARCHAR(64),
  create_time TIMESTAMP,
  update_by VARCHAR(64),
  update_time TIMESTAMP,
  remark VARCHAR(500)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_git_repo_member_repo_user
  ON sys_git_repository_member (repository_id, user_id);
CREATE INDEX IF NOT EXISTS idx_sys_git_repo_member_repo
  ON sys_git_repository_member (repository_id);
CREATE INDEX IF NOT EXISTS idx_sys_git_repo_member_user
  ON sys_git_repository_member (user_id);

-- 历史仓补默认 admin：create_by 能解析为用户名时写入；无法解析的仓在应用层 ensure
INSERT INTO sys_git_repository_member (repository_id, user_id, role, create_by, create_time)
SELECT r.repository_id, u.user_id, 'admin', 'migration', CURRENT_TIMESTAMP
FROM sys_git_repository r
INNER JOIN sys_user u ON u.user_name = r.create_by
WHERE r.create_by IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM sys_git_repository_member m
    WHERE m.repository_id = r.repository_id AND m.role = 'admin'
  );
