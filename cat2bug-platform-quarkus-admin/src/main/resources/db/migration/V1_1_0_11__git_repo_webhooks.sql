-- Cat2Bug 1.1.0 迁移 #11: git_repo_webhooks
-- 仓级出站 Webhook 配置与投递日志
CREATE TABLE IF NOT EXISTS sys_git_repository_webhook (
  webhook_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_id BIGINT NOT NULL,
  url VARCHAR(2000) NOT NULL,
  alias VARCHAR(128),
  secret_cipher VARCHAR(512) NOT NULL,
  events VARCHAR(256) NOT NULL,
  active TINYINT NOT NULL DEFAULT 1,
  create_by VARCHAR(64),
  create_time TIMESTAMP,
  update_by VARCHAR(64),
  update_time TIMESTAMP,
  remark VARCHAR(500)
);

CREATE INDEX IF NOT EXISTS idx_sys_git_repo_webhook_repo
  ON sys_git_repository_webhook (repository_id);
CREATE INDEX IF NOT EXISTS idx_sys_git_repo_webhook_repo_active
  ON sys_git_repository_webhook (repository_id, active);

CREATE TABLE IF NOT EXISTS sys_git_webhook_delivery (
  delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  webhook_id BIGINT NOT NULL,
  repository_id BIGINT NOT NULL,
  event VARCHAR(64) NOT NULL,
  delivery_guid VARCHAR(64) NOT NULL,
  request_headers_summary VARCHAR(2000),
  request_body CLOB,
  response_status INT,
  response_body_truncated CLOB,
  duration_ms BIGINT,
  success TINYINT NOT NULL DEFAULT 0,
  error_message VARCHAR(2000),
  create_time TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sys_git_webhook_delivery_webhook
  ON sys_git_webhook_delivery (webhook_id, create_time);
CREATE INDEX IF NOT EXISTS idx_sys_git_webhook_delivery_repo
  ON sys_git_webhook_delivery (repository_id, create_time);
CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_git_webhook_delivery_guid
  ON sys_git_webhook_delivery (delivery_guid);
