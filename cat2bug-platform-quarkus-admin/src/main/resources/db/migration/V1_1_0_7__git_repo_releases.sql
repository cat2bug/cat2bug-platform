-- Cat2Bug 1.1.0 迁移 #7: git_repo_releases
-- GitHub 风格发行版与附件元数据

CREATE TABLE IF NOT EXISTS sys_git_release (
  release_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_id BIGINT NOT NULL,
  tag_name VARCHAR(128) NOT NULL,
  target_commit_id VARCHAR(64),
  title VARCHAR(255) NOT NULL,
  body CLOB,
  draft INT NOT NULL DEFAULT 0,
  prerelease INT NOT NULL DEFAULT 0,
  publisher_id BIGINT,
  publisher_name VARCHAR(64),
  published_at TIMESTAMP,
  create_by VARCHAR(64),
  create_time TIMESTAMP,
  update_by VARCHAR(64),
  update_time TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_git_release_repo_tag ON sys_git_release (repository_id, tag_name);
CREATE INDEX IF NOT EXISTS idx_sys_git_release_repo ON sys_git_release (repository_id);

CREATE TABLE IF NOT EXISTS sys_git_release_asset (
  asset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  release_id BIGINT NOT NULL,
  repository_id BIGINT NOT NULL,
  file_name VARCHAR(255) NOT NULL,
  content_type VARCHAR(128),
  file_size BIGINT NOT NULL DEFAULT 0,
  storage_path VARCHAR(512) NOT NULL,
  create_by VARCHAR(64),
  create_time TIMESTAMP,
  update_by VARCHAR(64),
  update_time TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sys_git_release_asset_release ON sys_git_release_asset (release_id);
CREATE INDEX IF NOT EXISTS idx_sys_git_release_asset_repo ON sys_git_release_asset (repository_id);
